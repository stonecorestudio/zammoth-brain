"""The Imager's STEREOIZE (2026-10-28): side made from the mid, fitted to a reference imager measured
as a black box (James's pick, B) - our DSP, the reference's knob set.

Measured (headless through Pedalboard; the session's scratchpad has the probes and the fits):

* WIDTH is a pure mid/side gain - the mid untouched, the side x (1 + w/100) for w in -100..+100,
  flat, no latency. That is our `width` 0..2 exactly (it nulled to 0.000 dB): nothing here changes it.
* STEREOIZE acts only while the width is above unity. It ADDS side made from the mid:
  side_out = width x side_in + (width - 1) x (mid * h), linear (superposition held to -144 dB),
  where h is a sparse filter of +-taps - velvet noise - over the stereoize TIME (1..20 ms):
  four segments ending at EDGES of the time, the taps of each UNIT x AMPS[k] in size, the counts
  the reference's own counts at every whole ms (COUNTS). The mid
  is never touched, so the mono sum is the input's.
* OUR taps: one per equal slot of its segment, placed and signed by a 32-bit xorshift from a seed
  per whole ms (SEEDS), chosen so each octave's side energy sits within 1-2 dB of the reference's
  (it keeps the low end narrower than the top, as the reference does). The positions are times,
  so they scale with the rate.

The time is whole milliseconds (the knob snaps). `StereoizeLaw.h` is written from this file
(`python -m mix_engine.stereoize_law --write-header`); test_stereoize_law.py holds the two equal.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

AMPS = (1.0, 0.647, 0.412, 0.235)
EDGES = (0.02, 0.085, 0.31, 1.0)
UNIT = 0.2125
MS_MIN, MS_MAX, MS_DEFAULT = 1, 20, 6
# one seed per whole ms, 1..20 (fitted; see the docstring)
SEEDS = (5, 1519, 3736, 3004, 2740, 4800, 5428, 5762, 3687, 3756, 1189, 1087, 4807, 1131, 5781, 1393,
         991, 294, 2823, 2693)
# the reference's tap count in each segment, per whole ms 1..20 (measured)
COUNTS = ((1, 0, 1, 0), (1, 1, 1, 1), (2, 1, 2, 1), (2, 2, 2, 2), (3, 2, 3, 2), (3, 3, 3, 3), (4, 3, 4, 3), (4, 4, 4, 4), (5, 4, 5, 4), (5, 5, 5, 5), (6, 6, 6, 5), (7, 6, 6, 6), (7, 7, 7, 6), (8, 7, 7, 7), (8, 8, 8, 7), (9, 8, 8, 8), (9, 9, 9, 8), (10, 9, 9, 9), (10, 10, 10, 9), (11, 10, 11, 10))

HEADER = Path(__file__).resolve().parents[2] / "native" / "Source" / "StereoizeLaw.h"


def time_ms(ms: float) -> int:
    """The knob's whole-ms value."""
    return int(min(MS_MAX, max(MS_MIN, round(float(ms)))))


def counts(ms: int) -> tuple[int, int, int, int]:
    return COUNTS[ms - 1]


def _xorshift(state: int) -> int:
    state ^= (state << 13) & 0xFFFFFFFF
    state ^= state >> 17
    state ^= (state << 5) & 0xFFFFFFFF
    return state & 0xFFFFFFFF


def taps(ms: float, sr: float, seed: int | None = None) -> list[tuple[int, float]]:
    """[(delay in samples, gain)] for the given time and rate, gains for width 2 (w = +100)."""
    m = time_ms(ms)
    state = (SEEDS[m - 1] if seed is None else int(seed)) * 2654435761 % 4294967296 or 1
    n_end = m * 1e-3 * sr
    out: list[tuple[int, float]] = []
    lo = 0.0
    for amp, edge, n in zip(AMPS, EDGES, counts(m)):
        hi = edge * n_end
        if n:
            slot = (hi - lo) / n
            for i in range(n):
                state = _xorshift(state)
                frac = (state >> 8) / 16777216.0            # 24 bits, 0..1
                state = _xorshift(state)
                sign = 1.0 if state & 1 else -1.0
                pos = int(lo + (i + frac) * slot)
                out.append((pos, sign * UNIT * amp))
        lo = hi
    merged: dict[int, float] = {}
    for p, g in out:
        merged[p] = merged.get(p, 0.0) + g
    return sorted(merged.items())


def kernel(ms: float, sr: float, seed: int | None = None) -> np.ndarray:
    t = taps(ms, sr, seed)
    h = np.zeros(max(p for p, _ in t) + 1)
    for p, g in t:
        h[p] += g
    return h


def apply(x: np.ndarray, sr: float, width: float, on: bool = True, ms: float = MS_DEFAULT) -> np.ndarray:
    """(frames, 2) -> (frames, 2): the width (side x width) plus stereoize when on and width > 1."""
    mid = 0.5 * (x[:, 0] + x[:, 1])
    side = 0.5 * (x[:, 0] - x[:, 1]) * width
    if on and width > 1.0:
        k = width - 1.0
        made = np.zeros_like(mid)
        for p, g in taps(ms, sr):
            if p < len(mid):
                made[p:] += g * mid[: len(mid) - p]
        side = side + k * made
    return np.stack([mid + side, mid - side], axis=1)


def header_text() -> str:
    L = [
        "#pragma once",
        "// GENERATED by `python -m mix_engine.stereoize_law --write-header` from",
        "// server/mix_engine/stereoize_law.py - the Imager's Stereoize (that file says how it was",
        "// measured). Do not edit: change the Python table and write this again;",
        "// test_stereoize_law.py holds the two equal.",
        "",
        "#include <cstdint>",
        "",
        "namespace stereoizelaw",
        "{",
        "    static constexpr double kAmps[4]  = { " + ", ".join(repr(a) for a in AMPS) + " };",
        "    static constexpr double kEdges[4] = { " + ", ".join(repr(e) for e in EDGES) + " };",
        f"    static constexpr double kUnit = {UNIT!r};",
        f"    static constexpr int kMsMin = {MS_MIN}, kMsMax = {MS_MAX}, kMsDefault = {MS_DEFAULT};",
        "    static constexpr int kCounts[20][4] = { " + ", ".join("{ " + ", ".join(str(c) for c in row) + " }" for row in COUNTS) + " };",
        "    static constexpr uint32_t kSeeds[20] = { " + ", ".join(str(s) for s in SEEDS) + " };",
        "",
        "    inline int timeMs (double ms) noexcept",
        "    {",
        "        const double r = ms < 0.0 ? 0.0 : (double) (long long) (ms + 0.5);",
        "        return (int) (r < kMsMin ? kMsMin : (r > kMsMax ? kMsMax : r));",
        "    }",
        "",
        "    inline uint32_t xorshift (uint32_t s) noexcept",
        "    {",
        "        s ^= s << 13; s ^= s >> 17; s ^= s << 5; return s;",
        "    }",
        "",
        "    // The taps for a time and a rate, gains for width 2 (`stereoize_law.taps`): fills `pos` /",
        "    // `gain` (ascending, a shared position summed) and returns how many - at most kMaxTaps.",
        "    static constexpr int kMaxTaps = 64;",
        "    inline int taps (double ms, double sr, int* pos, double* gain) noexcept",
        "    {",
        "        const int m = timeMs (ms);",
        "        uint32_t state = (uint32_t) (kSeeds[m - 1] * 2654435761u);",
        "        if (state == 0) state = 1;",
        "        const double nEnd = m * 1e-3 * sr;",
        "        int n = 0;",
        "        double lo = 0.0;",
        "        for (int k = 0; k < 4; ++k)",
        "        {",
        "            const double hi = kEdges[k] * nEnd;",
        "            const int c = kCounts[m - 1][k];",
        "            if (c > 0)",
        "            {",
        "                const double slot = (hi - lo) / c;",
        "                for (int i = 0; i < c; ++i)",
        "                {",
        "                    state = xorshift (state);",
        "                    const double frac = (double) (state >> 8) / 16777216.0;",
        "                    state = xorshift (state);",
        "                    const double sign = (state & 1u) ? 1.0 : -1.0;",
        "                    const int p = (int) (lo + (i + frac) * slot);",
        "                    const double g = sign * kUnit * kAmps[k];",
        "                    int j = 0;",
        "                    while (j < n && pos[j] != p) ++j;",
        "                    if (j < n) gain[j] += g;",
        "                    else if (n < kMaxTaps) { pos[n] = p; gain[n] = g; ++n; }",
        "                }",
        "            }",
        "            lo = hi;",
        "        }",
        "        for (int a = 1; a < n; ++a)   // ascending by position",
        "            for (int b = a; b > 0 && pos[b - 1] > pos[b]; --b)",
        "            { const int tp = pos[b]; pos[b] = pos[b - 1]; pos[b - 1] = tp;",
        "              const double tg = gain[b]; gain[b] = gain[b - 1]; gain[b - 1] = tg; }",
        "        return n;",
        "    }",
        "}",
        "",
    ]
    return "\n".join(L)


if __name__ == "__main__":
    if "--write-header" in sys.argv:
        HEADER.write_text(header_text())
        print(f"wrote {HEADER}")
